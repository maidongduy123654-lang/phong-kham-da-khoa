USE clinic;

CREATE TABLE users (
  id VARCHAR(26) PRIMARY KEY, username VARCHAR(50) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL, role ENUM('PATIENT','RECEPTIONIST','DOCTOR','ADMIN') NOT NULL,
  is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE specialties (
  id VARCHAR(26) PRIMARY KEY, name VARCHAR(100) NOT NULL, description TEXT,
  price DECIMAL(12,2) DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
  id VARCHAR(26) PRIMARY KEY, user_id VARCHAR(26), full_name VARCHAR(100) NOT NULL,
  dob DATE, gender ENUM('MALE','FEMALE','OTHER'), phone VARCHAR(20) UNIQUE, cccd VARCHAR(20) UNIQUE,
  address TEXT, allergies JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE doctors (
  id VARCHAR(26) PRIMARY KEY, user_id VARCHAR(26) UNIQUE NOT NULL, full_name VARCHAR(100) NOT NULL,
  specialty_id VARCHAR(26) NOT NULL, room_no VARCHAR(20), bio TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (specialty_id) REFERENCES specialties(id)
);

CREATE TABLE schedules (
  id VARCHAR(26) PRIMARY KEY, doctor_id VARCHAR(26) NOT NULL, date DATE NOT NULL,
  start_time TIME NOT NULL, end_time TIME NOT NULL, is_booked BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (doctor_id) REFERENCES doctors(id) ON DELETE CASCADE
);

CREATE TABLE appointments (
  id VARCHAR(26) PRIMARY KEY, patient_id VARCHAR(26) NOT NULL, doctor_id VARCHAR(26) NOT NULL,
  schedule_id VARCHAR(26) NOT NULL, qr_code VARCHAR(100) UNIQUE NOT NULL,
  status ENUM('BOOKED','CHECKED_IN','CANCELLED','NO_SHOW') DEFAULT 'BOOKED', reason TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (patient_id) REFERENCES patients(id),
  FOREIGN KEY (doctor_id) REFERENCES doctors(id),
  FOREIGN KEY (schedule_id) REFERENCES schedules(id)
);

CREATE TABLE visits (
  id VARCHAR(26) PRIMARY KEY, appointment_id VARCHAR(26), patient_id VARCHAR(26) NOT NULL,
  doctor_id VARCHAR(26) NOT NULL,
  status ENUM('BOOKED','CHECKED_IN','WAITING_DOCTOR','IN_CONSULTATION','PENDING_LAB','COMPLETED','CANCELLED','NO_SHOW') DEFAULT 'BOOKED',
  queue_number INT, checked_in_at TIMESTAMP NULL, started_at TIMESTAMP NULL, completed_at TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE SET NULL,
  FOREIGN KEY (patient_id) REFERENCES patients(id), FOREIGN KEY (doctor_id) REFERENCES doctors(id)
);

CREATE TABLE queue_tickets (
  id VARCHAR(26) PRIMARY KEY, visit_id VARCHAR(26) NOT NULL, type ENUM('RECEPTION','DOCTOR') NOT NULL,
  number INT NOT NULL, status ENUM('WAITING','CALLED','SERVING','DONE','SKIPPED') DEFAULT 'WAITING',
  called_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (visit_id) REFERENCES visits(id) ON DELETE CASCADE
);

CREATE TABLE clinical_notes (
  id VARCHAR(26) PRIMARY KEY, visit_id VARCHAR(26) UNIQUE NOT NULL, symptoms TEXT,
  vitals JSON, diagnosis_icd10 VARCHAR(20), advice TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (visit_id) REFERENCES visits(id) ON DELETE CASCADE
);

CREATE TABLE drugs (
  id VARCHAR(26) PRIMARY KEY, name VARCHAR(200) NOT NULL, unit VARCHAR(50),
  price DECIMAL(12,2) DEFAULT 0, stock INT DEFAULT 0, contraindications JSON,
  is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prescriptions (
  id VARCHAR(26) PRIMARY KEY, visit_id VARCHAR(26) NOT NULL,
  diagnosis_icd10 VARCHAR(20), advice TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (visit_id) REFERENCES visits(id) ON DELETE CASCADE
);

CREATE TABLE prescription_items (
  id VARCHAR(26) PRIMARY KEY, prescription_id VARCHAR(26) NOT NULL, drug_id VARCHAR(26) NOT NULL,
  dosage VARCHAR(100), qty INT NOT NULL, days INT,
  FOREIGN KEY (prescription_id) REFERENCES prescriptions(id) ON DELETE CASCADE,
  FOREIGN KEY (drug_id) REFERENCES drugs(id)
);

CREATE TABLE lab_orders (
  id VARCHAR(26) PRIMARY KEY, visit_id VARCHAR(26) NOT NULL, items JSON NOT NULL, note TEXT,
  status ENUM('PENDING','IN_PROGRESS','COMPLETED','CANCELLED') DEFAULT 'PENDING',
  result JSON, approved_by VARCHAR(26), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMP NULL, FOREIGN KEY (visit_id) REFERENCES visits(id) ON DELETE CASCADE
);

CREATE TABLE invoices (
  id VARCHAR(26) PRIMARY KEY, visit_id VARCHAR(26) NOT NULL, type ENUM('CONSULT','LAB','MEDICINE') NOT NULL,
  amount DECIMAL(12,2) NOT NULL, method ENUM('CASH','CARD','TRANSFER') DEFAULT 'CASH',
  status ENUM('PENDING','PAID','CANCELLED') DEFAULT 'PENDING', note TEXT, paid_at TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (visit_id) REFERENCES visits(id) ON DELETE CASCADE
);

CREATE TABLE audit_logs (
  id VARCHAR(26) PRIMARY KEY, user_id VARCHAR(26), action VARCHAR(100) NOT NULL,
  entity VARCHAR(50), entity_id VARCHAR(26), metadata JSON,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
